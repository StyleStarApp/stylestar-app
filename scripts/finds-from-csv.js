// finds-from-csv.js — turns her Amazon Finds spreadsheet into the hand-written
// .dc-item markup on the /finds screen.
//
//   node scripts/finds-from-csv.js data/amazon-finds.csv           # dry run, shows the diff
//   node scripts/finds-from-csv.js data/amazon-finds.csv --write   # writes index.html
//   node scripts/finds-from-csv.js --check                         # does the page still match the CSV?
//
// ▶▶ WHY THIS EXISTS: she asked to add Finds pieces in BATCHES rather than one
// at a time (2026-09-11, "i want to do a larger batch"). Hand-editing markup is
// fine for three pieces and is how the Edit is still maintained; it stops being
// fine at twenty.
//
// 🚨🚨 THE TRAP THIS SCRIPT EXISTS TO NOT FALL INTO, AND IT HAS ALREADY BEEN
// PAID FOR ONCE: every .dc-* anchor is AMBIGUOUS now that two screens use the
// same markup, and the FIRST occurrence in the file is always the EDIT'S. Two
// of her Amazon pieces were once inserted above `<div class="dc-sign">` and
// landed on the Edit. ▶ SO THE SCREEN IS SLICED FIRST and the markers below are
// found INSIDE that slice, never in the whole file.
//
// ⚠️ CLAUDE MUST NEVER PICK THE PRODUCTS. The disclosure on this page says every
// piece is personally selected by the founder. This script renders HER rows; it
// invents nothing, and an empty category column means no categories at all.
import fs from 'fs';
import path from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const IDX = path.join(ROOT, 'index.html');
const HEADER = ['name', 'store', 'price', 'note', 'url', 'category'];
const START = '<!-- FINDS:ITEMS:START — generated by scripts/finds-from-csv.js, do not hand-edit -->';
const END = '<!-- FINDS:ITEMS:END -->';

// Amazon links arrive carrying navigation and order-history crumbs. th=1/psc=1
// pin a colour or size variation; ref=ppx_yo2ov_ comes straight off her own
// orders page. Canonical is the bare /dp/<ASIN> and nothing else.
const ASIN = /(?:\/dp\/|\/gp\/product\/|\/product\/)([A-Z0-9]{10})(?:[/?#]|$)/i;

// ---- the same CSV reader the catalog importer uses -------------------------
function parseCsv(text) {
  const rows = []; let row = [], field = '', inQ = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (inQ) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else inQ = false; }
      else field += c;
    } else if (c === '"') inQ = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(field); field = '';
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
    } else field += c;
  }
  if (field !== '' || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;').replace(/·/g, '&middot;');

/* 🚨🚨 THE PRICE RULE, AND IT IS HER OWN ASYMMETRY ONE STANDING A STEP FURTHER OUT.
   Her rule for the Edit is REGULAR PRICE, NEVER THE SALE PRICE, because arriving
   to find a piece CHEAPER than billed feels lucky and arriving to find it DEARER
   feels misled. Only one of those is recoverable.
   ▶ So the rounding is CEILING, never nearest. Nearest would print ~$16 for a
   $16.25 piece and she would arrive to find it dearer than the page said — the
   exact feeling that rule exists to prevent. Ceiling can only ever surprise her
   the good way.
   ▶ AND WHY IT IS ROUNDED AT ALL, which is a Finds-only argument: Amazon product
   pages are BOT-WALLED (measured 2026-09-11 — one returns an automated-access
   wall, the other 166KB with no price in it), so an Amazon price can never be
   verified from here and moves daily. A tilde is honest about a number nobody
   can check. The Edit's shops CAN be read, so the Edit keeps exact prices. */
export function renderPrice(raw) {
  const s = String(raw || '').trim();
  if (!s) return '';                       // optional, and empty means NO price shown
  // A price cell may carry a trailing qualifier — her Gold Ponytail Cuff is
  // "9.99 for 4" — so the number is rounded and the words are kept verbatim.
  const m = /^\$?\s*([0-9]+(?:\.[0-9]+)?)\s*(.*)$/.exec(s);
  if (!m) return null;                     // unparseable: the caller errors rather than guessing
  const shown = '~$' + Math.ceil(parseFloat(m[1])) + (m[2] ? ' ' + m[2] : '');
  return `<span class="dc-price" data-price="${esc(s)}">${esc(shown)}</span>`;
}

const BAG = '<svg class="dc-bag" viewBox="0 0 24 24" fill="none" stroke="#0FA6B6" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round"><path d="M5.8 8.5 h12.4 l-0.8 10.6 a1.2 1.2 0 0 1 -1.2 1.1 H7.8 a1.2 1.2 0 0 1 -1.2 -1.1 Z"/><path d="M8.3 8.5 C8.3 4.2 15.7 4.2 15.7 8.5"/><path d="M12 11.9 L12.5 13.3 L14 13.35 L12.85 14.25 L13.25 15.65 L12 14.8 L10.75 15.65 L11.15 14.25 L10 13.35 L11.5 13.3 Z" fill="#0FA6B6" stroke="none"/></svg>';

function renderItem(r) {
  const price = renderPrice(r.price);
  const meta = `<div class="dc-item-meta"><span class="dc-store">${esc(r.store || 'Amazon')}</span>${price}</div>`;
  // ⚠️ rel="sponsored noopener" on every outbound link or scratchpad/affq.js
  // fails — and it should, an untagged outbound anchor is money on the floor.
  // ▶ The href stays RAW. _wlDecorateEdit() adds ?tag= at runtime from the one
  // _AMZ_TAG constant, which is what lets her paste her id in a single place.
  return [
    '    <div class="dc-item">',
    '      <span class="dc-item-star">⭐</span>',
    `      <div class="dc-item-name">${esc(r.name)}</div>`,
    '      ' + meta,
    `      <div class="dc-item-note">${esc(r.note)}</div>`,
    `      <a class="dc-item-btn" href="${r.url}" target="_blank" rel="sponsored noopener">${BAG}Shop this item <span class="dc-arr">&rarr;</span></a>`,
    '    </div>',
  ].join('\n');
}

export function render(rows) {
  // Her spreadsheet's row order IS the page order, and the order categories
  // first APPEAR is the order they are laid out in — so she rearranges the page
  // by rearranging her rows, with nobody to ask and nothing to configure.
  const groups = [];
  for (const r of rows) {
    const key = r.category || '';
    let g = groups.find(x => x.key === key);
    if (!g) groups.push(g = { key, items: [] });
    g.items.push(r);
  }
  // An uncategorised group renders with NO heading, so a spreadsheet with the
  // column left empty produces exactly the flat page she has today.
  const out = [];
  for (const g of groups) {
    if (g.key) out.push(`    <div class="dc-cat">${esc(g.key)}</div>`);
    for (const it of g.items) out.push(renderItem(it));
  }
  return out.join('\n\n');
}

// ---- read + validate -------------------------------------------------------
export function load(csvPath) {
  const rows = parseCsv(fs.readFileSync(csvPath, 'utf8'));
  if (!rows.length) throw new Error('the CSV is empty');
  const header = rows[0].map(h => h.trim().toLowerCase());
  if (header.join(',') !== HEADER.join(',')) {
    throw new Error(`header must be exactly:\n  ${HEADER.join(',')}\ngot:\n  ${header.join(',')}`);
  }
  const errors = [], out = [], seen = new Map();
  rows.slice(1).forEach((cells, i) => {
    const line = i + 2;
    const r = {}; HEADER.forEach((h, k) => r[h] = String(cells[k] === undefined ? '' : cells[k]).trim());
    if (!r.name) return errors.push(`row ${line}: no name`);
    if (!r.url) return errors.push(`row ${line}: no Amazon link or ASIN`);
    // She may paste a full link or just the ASIN — both land on the same page.
    let asin = (ASIN.exec(r.url) || [])[1];
    if (!asin && /^[A-Z0-9]{10}$/i.test(r.url)) asin = r.url;
    if (!asin) return errors.push(`row ${line}: "${r.url}" is not an Amazon product link or a 10-character ASIN`);
    asin = asin.toUpperCase();
    if (seen.has(asin)) return errors.push(`row ${line}: ${asin} is already row ${seen.get(asin)} ("${r.name}")`);
    seen.set(asin, line);
    r.url = 'https://www.amazon.com/dp/' + asin;
    r.asin = asin;
    if (renderPrice(r.price) === null) return errors.push(`row ${line}: price "${r.price}" is not a number (leave it empty for no price)`);
    out.push(r);
  });
  if (errors.length) throw new Error(errors.join('\n'));
  return out;
}

// ---- splice it into the one screen it belongs to ---------------------------
export function region(html) {
  const s0 = html.indexOf('id="s-finds"');
  if (s0 < 0) throw new Error('cannot find the s-finds screen in index.html');
  const s1 = html.indexOf('id="s-shop"', s0);
  const slice = html.slice(s0, s1 < 0 ? html.length : s1);
  const a = slice.indexOf(START), b = slice.indexOf(END);
  if (a < 0 || b < 0) throw new Error('the FINDS:ITEMS markers are missing from the s-finds screen');
  return { from: s0 + a + START.length, to: s0 + b };
}

const names = h => {
  const s0 = h.indexOf('id="s-finds"'), s1 = h.indexOf('id="s-shop"', s0);
  return [...h.slice(s0, s1 < 0 ? h.length : s1).matchAll(/<div class="dc-item-name">([\s\S]*?)<\/div>/g)].map(m => m[1]);
};

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  const args = process.argv.slice(2);
  const write = args.includes('--write');
  const check = args.includes('--check');
  const allowRemovals = args.includes('--allow-removals');
  const csvPath = args.find(a => !a.startsWith('--')) || path.join(ROOT, 'data/amazon-finds.csv');

  const html = fs.readFileSync(IDX, 'utf8');
  let rows;
  try { rows = load(csvPath); }
  catch (e) { console.error('✗ ' + e.message); process.exit(1); }

  const { from, to } = region(html);
  const next = html.slice(0, from) + '\n' + render(rows) + '\n    ' + html.slice(to);

  const before = names(html), after = names(next);
  const gone = before.filter(n => !after.includes(n));
  const added = after.filter(n => !before.includes(n));

  if (check) {
    const same = next === html;
    console.log(same ? '✓ the /finds page matches the CSV' : '✗ the /finds page does NOT match the CSV — run with --write');
    process.exit(same ? 0 : 1);
  }

  console.log(`  ${before.length} pieces on the page → ${after.length} from the CSV`);
  added.forEach(n => console.log('  + ' + n));
  gone.forEach(n => console.log('  - ' + n));
  const cats = [...new Set(rows.map(r => r.category).filter(Boolean))];
  console.log(cats.length ? `  categories: ${cats.join(' · ')}` : '  no categories (flat list)');

  // ⚠️ A SPREADSHEET SENT WITH ONE SHEET MISSING WOULD SILENTLY DELETE HER PAGE.
  // Removals are real and allowed — she retires pieces — but never by accident.
  if (gone.length && !allowRemovals && !check) {
    console.error(`\n✗ that would REMOVE ${gone.length} piece(s) from her page.`);
    console.error('  If that is deliberate, re-run with --allow-removals.');
    process.exit(1);
  }

  if (!write) { console.log('\n  (dry run — pass --write to apply)'); process.exit(0); }

  fs.writeFileSync(IDX, next);
  // ⭐ THE CHEAP HABIT THAT CATCHES THE WRONG-SCREEN BUG EVERY TIME: print BOTH
  // counts after any curated-page edit, before doing anything else.
  const v = fs.readFileSync(IDX, 'utf8');
  const count = (id, nextId) => {
    const i = v.indexOf(`id="${id}"`), j = v.indexOf(`id="${nextId}"`, i);
    return (v.slice(i, j < 0 ? v.length : j).match(/<div class="dc-item">/g) || []).length;
  };
  console.log(`\n✓ written. The Edit holds ${count('s-dream', 's-finds')} pieces; Amazon Finds holds ${count('s-finds', 's-shop')}.`);
  console.log('  ▶ now run: node scripts/sitemap-lastmod.js --write');

}
